/** Tiny in-app translation layer. English text is the key; unknown keys fall back to English. */
object Lang {
    var current by mutableStateOf("en")
        private set

    fun init(context: Context) {
        current = context.getSharedPreferences("bloodbridge", Context.MODE_PRIVATE).getString("lang", "en") ?: "en"
    }

    fun set(context: Context, lang: String) {
        current = lang
        context.getSharedPreferences("bloodbridge", Context.MODE_PRIVATE).edit().putString("lang", lang).apply()
    }
}

fun t(en: String): String = if (Lang.current == "bn") (bnStrings[en] ?: en) else en

/** Display label for stored English values (districts, gender, urgency, status, org type). */
